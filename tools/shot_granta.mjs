// Renders the Granta in headless Chrome: four views, a close-up, another paint colour and the outlander for comparison.
import { chromium } from 'playwright-core';
import fs from 'fs';
const url = process.argv[2] || 'http://127.0.0.1:8080/index.html';
const out = process.argv[3] || 'shots';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 412, height: 860 }, deviceScaleFactor: 2, reducedMotion: 'reduce' });
const logs = [];
page.on('console', m => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', e => logs.push('PAGEERROR: ' + e.message));
const shot = async (n) => { await page.waitForTimeout(2500); await page.screenshot({ path: `${out}/${n}.png` }); };
const click = (sel) => page.evaluate(s => document.querySelector(s)?.click(), sel);
const view = (v) => click(`.views button[data-view="${v}"]`);
const setup = async (o) => { await page.evaluate((o) => { localStorage.clear(); for (const k in o) localStorage.setItem('f7box.' + k, JSON.stringify(o[k])); }, o); await page.reload(); await page.waitForTimeout(12000); };
await page.goto(url); await page.waitForTimeout(3000);
await setup({ car: 'granta', wxMode: 'off', sel: 'm3-l', items: [] });
await shot('g1-q'); await view('side'); await shot('g2-side'); await view('rear'); await shot('g3-rear'); await view('top'); await shot('g4-top');
await view('q'); await page.mouse.move(206, 400); for (let i = 0; i < 6; i++) { await page.mouse.wheel(0, -300); await page.waitForTimeout(150); } await shot('g5-close');
await setup({ car: 'granta', wxMode: 'off', sel: 'lx-175', items: [], 'granta.color': '#6E1520' });
await shot('g6-red-lux'); await click('#paintBtn'); await shot('g7-menu');
await setup({ car: 'granta', sel: 'm3-l', items: [] });
await shot('g8-weather');
fs.writeFileSync(`${out}/console.txt`, logs.join('\n'));
await browser.close();
